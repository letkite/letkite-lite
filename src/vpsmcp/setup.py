def _finish(domain, mcp_path, bind_host, bind_port, email, admin_user,
            generated_password, argv, flag) -> int:
    def warn_local(m): warn(m)
    public_url = f"https://{domain}"
    bind = f"{bind_host}:{bind_port}"

    # ---- DNS ----
    say("DNS")
    ips = _resolve(domain)
    mine = _public_ip()
    if not ips:
        warn(f"{domain} does not resolve; add an A record to {mine or 'this host'} "
             f"or the certificate cannot be issued")
    elif mine and mine not in ips:
        warn(f"{domain} resolves to {', '.join(ips)} but this host is {mine}; "
             f"certificate issuance will fail")
    else:
        ok(f"{domain} → {', '.join(ips)}")
    if any(":" in i for i in ips):
        warn("AAAA record present: broken IPv6 causes intermittent failures")

    # ---- systemd ----
    say("systemd unit")
    Path("/etc/systemd/system/vpsmcp.service").write_text(_systemd_unit(), encoding="utf-8")
    # Egress proxy unit is installed but left disabled; enable it only after
    # `vpsmcp proxy-password` sets a credential.
    Path("/etc/systemd/system/vpsmcp-proxy.service").write_text(
        _proxy_systemd_unit(), encoding="utf-8")
    have_systemd = Path("/run/systemd/system").is_dir()
    if not have_systemd:
        warn("not booted with systemd (container?); unit written but not started")
        dim(f"run manually: {APP}/.venv/bin/python -m vpsmcp serve")
    else:
        subprocess.run(["systemctl", "daemon-reload"], capture_output=True)
        subprocess.run(["systemctl", "enable", "vpsmcp"], capture_output=True)
        subprocess.run(["systemctl", "restart", "vpsmcp"], capture_output=True)
        time.sleep(2)
        st = subprocess.run(["systemctl", "is-active", "vpsmcp"],
                            capture_output=True, text=True).stdout.strip()
        if st == "active":
            ok("vpsmcp service active")
        else:
            bad(f"vpsmcp service {st or 'failed to start'} - journalctl -u vpsmcp -n 40")

    # ---- Caddy ----
    if not flag("--no-caddy"):
        say("reverse proxy")
        if not caddymod.installed():
            dim("installing Caddy...")
            good, msg = caddymod.apt_install()
            (ok if good else bad)(f"Caddy {msg}")
        if caddymod.installed():
            allow_cidrs = tuple(argv[i + 1] for i, a in enumerate(argv)
                                if a == "--allow-cidr" and i + 1 < len(argv))
            conf = caddymod.render(host=domain, upstream=bind, mcp_path=mcp_path, email=email,
                                   lock_anthropic=flag("--lock-anthropic"),
                                   allow_cidrs=allow_cidrs)
            good, msg = caddymod.write(conf)
            (ok if good else bad)(msg)
            if good:
                good, msg = caddymod.reload()
                (ok if good else bad)(f"Caddy {msg}")
    else:
        warn("--no-caddy: configure the reverse proxy yourself")

    # ---- self-test ----
    fails = selftest(public_url, mcp_path, bind)

    # ---- optional: enroll the gateway itself ----
    if flag("--self-enroll"):
        say("enrolling the gateway as a node")
        url = f"http://{bind_host}:{bind_port}/enroll/install.sh"
        r = subprocess.run(["bash", "-c",
                            f"curl -sSf '{url}' | bash -s -- --alias gw --tags gateway,infra "
                            f"--user gwops"], capture_output=True, text=True)
        (ok if r.returncode == 0 else bad)(
            "gateway enrolled as a node" if r.returncode == 0
            else f"enrollment failed: {(r.stdout + r.stderr).strip()[-200:]}")

    # ---- summary ----
    print()
    if generated_password:
        print(f"{C['b']}Admin password (shown once - save it now){C['x']}")
        print(f"    username  {admin_user}")
        print(f"    password  {generated_password}\n")
    print(f"{C['b']}Add a custom MCP connector with this URL:{C['x']}")
    print(f"    {public_url}{mcp_path}")
    dim("Claude: Settings -> Connectors. Kimi and GLM: add an MCP server with the")
    dim("same URL, sign in on the page it opens, then approve the scopes.")
    dim("`sudo vpsmcp clients` lists the clients accepted; if one is turned away")
    dim("because of its callback URL, `sudo vpsmcp redirects` prints it.\n")
    print(f"{C['b']}Enroll a node (run on the target machine):{C['x']}")
    print(f"    curl -sSf {public_url}/enroll/install.sh | sudo bash")
    print(f"    curl -sSf {public_url}/enroll/install.sh | sudo bash -s -- --alias web-01 --tags prod\n")
    if fails:
        print(f"{C['y']}{fails} self-test check(s) failed{C['x']} - usually DNS not "
              f"propagated yet, or ports 80/443 blocked by a firewall.")
        print("    re-run after fixing: sudo vpsmcp setup --domain " + domain + " -y")
    else:
        print(f"{C['g']}All checks passed.{C['x']}")
    return 0 if fails == 0 else 1
